const KM_DIGITS = ['០', '១', '២', '៣', '៤', '៥', '៦', '៧', '៨', '៩'];
const KM_MONTHS = ['មករា', 'កុម្ភៈ', 'មីនា', 'មេសា', 'ឧសភា', 'មិថុនា', 'កក្កដា', 'សីហា', 'កញ្ញា', 'តុលា', 'វិច្ឆិកា', 'ធ្នូ'];
const EN_MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

/** Current language, persisted separately so it survives logout / reset. */
let LANG = (() => { try { return localStorage.getItem('hf_lang') || 'km'; } catch (e) { return 'km'; } })();

function setLang(l) {
  LANG = l;
  try { localStorage.setItem('hf_lang', l); } catch (e) { /* ignore */ }
  document.documentElement.lang = l;
}

/** Translate a key, replacing {placeholders}. */
function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]);
  if (s === undefined) s = I18N.km[key];
  if (s === undefined) { console.warn('[i18n] missing', key); s = key; }
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}

/** Small counters (days, badges) use Khmer digits in Khmer, like the Figma design. */
function n(num) {
  const s = String(num);
  return LANG === 'km' ? s.replace(/[0-9]/g, (d) => KM_DIGITS[d]) : s;
}

/** Large quantities stay in Latin digits for readability (as in the Figma dashboard). */
function kgFmt(v) {
  const r = Math.round(v * 10) / 10;
  return r.toLocaleString('en-US', { maximumFractionDigits: 1 });
}

function money(v) {
  return '$' + (Math.round(v * 100) / 100).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

/** 27 កញ្ញា 2026  /  27 Sep 2026 */
function fmtDate(iso) {
  if (!iso) return '—';
  const d = new Date(iso);
  const m = LANG === 'km' ? KM_MONTHS[d.getMonth()] : EN_MONTHS[d.getMonth()];
  return `${d.getDate()} ${m} ${d.getFullYear()}`;
}

function fmtTime(iso) {
  const d = new Date(iso);
  return `${String(d.getHours()).padStart(2, '0')}:${String(d.getMinutes()).padStart(2, '0')}`;
}

function timeAgo(iso) {
  const diff = (Date.now() - new Date(iso).getTime()) / 60000;
  if (diff < 1) return t('justNow');
  if (diff < 60) return t('minutesAgo', { n: n(Math.floor(diff)) });
  if (diff < 60 * 24) return t('hoursAgo', { n: n(Math.floor(diff / 60)) });
  return t('daysAgo', { n: n(Math.floor(diff / 1440)) });
}

/** Pick the localized name from an object with {km, en}. */
function L(obj) {
  if (!obj) return '';
  if (typeof obj === 'string') return obj;
  return obj[LANG] || obj.km || obj.en || '';
}
